def pct(c, n):
    """Share with its Wilson interval, as LaTeX. One place after the point:
    the intervals are 2-4 points wide, so a second place is false precision."""
    if not n:
        return "---"
    lo, hi = wilson(c, n)
    return "\\textbf{%.1f\\%%} & [%.1f, %.1f]" % (100.0 * c / n, 100 * lo, 100 * hi)


# --------------------------------------------------------------- B1: space ---

def action_space():
    """The controlled within-session measurement. The paper's headline."""
    import own_action_space as oas

    archive = os.path.join(DATA, "denials")
    calls, _n_sessions = oas.calls_in(archive)

    rows = []
    for label, sel in (("Shell (\\texttt{Bash}, \\texttt{PowerShell})",
                        lambda c: c["space"] == "shell"),
                       ("Structured tools (\\texttt{Read}, \\texttt{Write}, "
                        "\\texttt{Edit}, \\texttt{Glob}, \\texttt{Grep})",
                        lambda c: c["space"] == "tool")):
        for mutating in (False, True):
            sub = [c for c in calls
                   if sel(c) and (not mutating or not c["read_only"])]
            n = len(sub)
            refused = sum(1 for c in sub if c["refused"])
            shown = label
            if mutating and label.startswith("Structured"):
                # The mutating block names only the structured tools that
                # actually occur in it; Read, Glob and Grep are read-only.
                seen = collections.Counter(c["tool"] for c in sub)
                shown = "Structured tools (%s)" % ", ".join(
                    "\\texttt{%s}" % t for t, _k in seen.most_common())
            rows.append((shown, mutating, n, refused))

    def block(mutating):
        out = []
        for label, m, n, refused in rows:
            if m != mutating:
                continue
            out.append("%s & %s & %d & %s \\\\" %
                       (label, "{:,}".format(n), refused, pct(refused, n)))
        import collections as _c
        import stats as _st
        per = _c.defaultdict(lambda: [0, 0, 0, 0])
        for c in calls:
            if mutating and c["read_only"]:
                continue
            slot = 0 if c["space"] == "shell" else (2 if c["space"] == "tool"
                                                    else None)
            if slot is None:
                continue
            per[c["session"]][slot] += 1 if c["refused"] else 0
            per[c["session"]][slot + 1] += 1
        clusters = [(v[0], v[1], v[2], v[3]) for v in per.values()]
        p1, p2, d, lo, hi, K = _st.cluster_diff_paired(clusters)
        if K < 2:
            raise RuntimeError("cannot cluster the action-space difference: "
                               "%d session(s)" % K)
        out.append("\\midrule")
        out.append("Difference & & & \\textbf{%+.1f pts} & [%+.1f, %+.1f] \\\\"
                   % (100 * d, 100 * lo, 100 * hi))
        return "\n".join(out)

    return HEADER + r"""\begin{tabular}{lrrrr}
\toprule
Action space & Calls & Intercepted & Share & 95\%% CI \\
\midrule
\multicolumn{5}{l}{\emph{Every recorded call}} \\
%s
\midrule
\multicolumn{5}{l}{\emph{Mutating calls only --- read-only excluded from both sides}} \\
%s
\bottomrule
\end{tabular}
""" % (block(False), block(True))


# ------------------------------------------------------------ B3: residual ---

def residual():
    """The decidability x recoverability grid, with its denominator stated."""
    import taxonomy_robustness as tr

    grid, total, unlabelled = tr.reach_by_class("violations.jsonl")

    local_c1 = grid.get(("Local", "C1"), 0)
    ext_c1 = grid.get(("External", "C1"), 0)
    local_c2 = grid.get(("Local", "C2"), 0)
    ext_c2 = grid.get(("External", "C2"), 0)
    labelled = local_c1 + ext_c1 + local_c2 + ext_c2
    lo, hi = wilson(ext_c2, total)

    return HEADER + r"""\begin{tabular}{lrr}
\toprule
 & Recoverable (local) & Irreversible (external) \\
\midrule
Decidable in advance   & %d & %d \\
Undecidable in advance & %d & \textbf{%d \quad(neither reaches)} \\
\bottomrule
\end{tabular}
%%
%% n=%d of %d violating steps. The remaining %d carry no reachability label
%% (C0 placeholder content and C3 claims, neither of which has a filesystem
%% effect to classify). The neither-reaches cell is %.1f%% of the full corpus,
%% Wilson 95%% CI [%.1f, %.1f].
%%
%% This grid is drawn for StepShield ONLY. ATBench has no Local column - every
%% one of its 4,726 steps mutates a third party - so a 2x2 for it would be a
%% 1xN table with two cells invented.
""" % (local_c1, ext_c1, local_c2, ext_c2,
       labelled, total, unlabelled,
       100.0 * ext_c2 / total, 100 * lo, 100 * hi)


# ------------------------------------------------------- A6: the two rates ---

def composition():
    """C1 share per corpus, at BOTH levels, because conflating them was a real
    error in the draft: 6.7% is a trajectory-level number and the prose around
    it read as step-level."""
    import taxonomy_robustness as tr

    rows = tr.step_and_trajectory_rates()
    body = []
    for name, steps, c1_steps, trajs, c1_trajs in rows:
        body.append("%s & %s & %d & %.2f\\%% & %s & %d & %.2f\\%% \\\\"
                    % (name, "{:,}".format(steps), c1_steps,
                       100.0 * c1_steps / steps if steps else 0,
                       "{:,}".format(trajs), c1_trajs,
                       100.0 * c1_trajs / trajs if trajs else 0))

    return HEADER + r"""\begin{tabular}{lrrrrrr}
\toprule
& \multicolumn{3}{c}{Per step} & \multicolumn{3}{c}{Per trajectory} \\
\cmidrule(lr){2-4}\cmidrule(lr){5-7}
Corpus & $n$ & C1 & Share & $n$ & $\geq$1 C1 & Share \\
\midrule
%s
\bottomrule
\end{tabular}
%%
%% Both levels are printed on purpose. A trajectory-level rate answers "could a
%% gate have interrupted this episode at all"; a step-level rate answers "what
%% fraction of what the agent did was refusable". The first is the more
%% generous of the two and is the one this literature usually reports.
""" % "\n".join(body)


# ------------------------------------------------------ A7: effort rungs ---

def effort():
    """Override rate by model and effort rung."""
    import models as md

    # models.py resolves `paper/data` relative to the working directory; every
    # other builder here uses the absolute DATA, and tables.py is run from
    # build.sh's scratch tree as often as from the repo root.
    md.DATA = DATA

    order = ["sonnet", "opus"]
    pretty = {"default": "Default", "low": "Low", "medium": "Medium",
              "high": "High", "xhigh": "Extra-high", "max": "Max"}

    body, notes = [], []
    for model in order:
        rungs = md.EFFORT[model]
        cells, sessions = [], []
        for label, arch in rungs:
            rows, n_sessions = md.arm_rows(arch)
            if not rows:
                cells.append("\\emph{not collected}")
                sessions.append("---")
                continue
            k = sum(1 for r in rows if r["response"] == "Overrode")
            cells.append("%.1f\\%% ($n{=}%d$)" % (100.0 * k / len(rows),
                                                  len(rows)))
            sessions.append("%d" % n_sessions)
        body.append("%-6s & %s \\\\" % (model.capitalize(), " & ".join(cells)))

        # The pre-specified contrast, from the same rows the cells came from.
        d_rows, _ = md.arm_rows(dict(rungs)["default"])
        m_rows, _ = md.arm_rows(dict(rungs)["max"])
        if d_rows and m_rows:
            kd = sum(1 for r in d_rows if r["response"] == "Overrode")
            km = sum(1 for r in m_rows if r["response"] == "Overrode")
            lo, hi = newcombe(kd, len(d_rows), km, len(m_rows))
            import stats as _st
            pbar = (kd + km) / float(len(d_rows) + len(m_rows))
            contrast = ("$%+.1f$ pts $[%+.1f, %+.1f]$, MDD $%.1f$"
                        % (100.0 * (kd / float(len(d_rows))
                                    - km / float(len(m_rows))),
                           100 * lo, 100 * hi,
                           100 * _st.mdd(len(d_rows), len(m_rows), pbar)))
        else:
            contrast = "not computable"
        notes.append((model.capitalize(), ", ".join(sessions), contrast))

    head = " & ".join(pretty[k] for k, _ in md.EFFORT[order[0]])
    foot = [
        "\\multicolumn{7}{l}{\\footnotesize Sessions with recorded work, in "
        "column order: %s %s;} \\\\" % (notes[0][0], notes[0][1]),
        "\\multicolumn{7}{l}{\\footnotesize %s %s. A session that produced only "
        "harness bookkeeping is not one.} \\\\" % (notes[1][0], notes[1][1]),
        "\\multicolumn{7}{l}{\\footnotesize Pooled default-vs-max: %s %s;} \\\\"
        % (notes[0][0], notes[0][2]),
        "\\multicolumn{7}{l}{\\footnotesize %s %s. Small cells should not be "
        "read as point estimates.} \\\\" % (notes[1][0], notes[1][2]),
    ]

    return HEADER + r"""\begin{tabular}{lcccccc}
\toprule
& %s \\
\midrule
%s
\midrule
%s
\bottomrule
\end{tabular}
""" % (head, "\n".join(body), "\n".join(foot))


# ----------------------------------------------------------- A2: ablation ---

def ablation():
    """The four-arm refusal ladder."""
    import ablation as ab

    rows = []
    for label, archive in ab.ARMS:
        path = os.path.join(DATA, archive)
        events = responses.denials_in(path) if os.path.isdir(path) else []
        rows.append((label, events))

    pretty = {
        "terse": "Terse (bare refusal)",
        "explain": "Explain (adds the reason)",
        "padded": "Padded (no reason, full's length)",
        "defer": "Defer (reason $+$ instruction to stop)",
        "full": "Full (reason $+$ named override)",
        "control": "Full, no system note (control)",
    }

    body, missing = [], []
    for label, events in rows:
        if not events:
            missing.append(label)
            body.append("%s & \\multicolumn{4}{c}{\\emph{not collected}} \\\\"
                        % pretty.get(label, label))
            continue
        n = len(events)
        cells = []
        for key in ("Overrode", "Rewrote", "RetriedIdentical"):
            c = sum(1 for r in events if r["response"] == key)
            cells.append("%.1f\\%%" % (100.0 * c / n))
        body.append("%s & %d & %s \\\\"
                    % (pretty.get(label, label), n, " & ".join(cells)))

    note = ""
    if missing:
        note = ("%%\n%% INTERIM: %s not collected. Re-run tables.py after\n"
                "%% run-all.sh completes; do not submit this table as it stands.\n"
                % ", ".join(missing))

    return HEADER + r"""\begin{tabular}{lrrrr}
\toprule
Refusal text & Events & Took override & Reused tool & Identical retry \\
\midrule
%s
\bottomrule
\end{tabular}
%s""" % ("\n".join(body), note)


# ------------------------------------------------------ A3: cross-vendor ---

def crossvendor():
    """Ten model cells, three vendors, a second harness, one refusal text."""
    import cross_vendor as cv

    m = cv.measure()
    rows = [c for c in m["cells"] if c["n"]]
    if not rows:
        raise SystemExit(
            "  cross-vendor: no agy archives on this machine; nothing to "
            "check.")

    # "Open weights", not "OpenAI". gpt-oss-120b is not a vendor-hosted OpenAI
    # product and printing a vendor name beside two that ARE vendor-hosted is
    # the mis-framing the review flagged. The column says what was served.
    pretty = {"anthropic": "Anthropic", "google": "Google",
              "open-weights": "Open weights"}
    row = (r"\texttt{%s} & %s & %d & %d & \textbf{%.1f\%%} & [%.1f, %.1f] \\")
    body = []
    for c in sorted(rows, key=lambda r: (r["vendor"], -r["pct"])):
        body.append(row % (c["cell"].replace("_", r"\_"),
                           pretty.get(c["vendor"], c["vendor"]),
                           c["n"], c["k"], c["pct"], c["lo"], c["hi"]))
    p = m["pooled"]
    body.append(r"\midrule")
    body.append(r"Pooled & --- & %d & %d & \textbf{%.1f\%%} & [%.1f, %.1f] \\"
                % (p["n"], p["k"], p["pct"], p["lo"], p["hi"]))

    return HEADER + r"""\begin{tabular}{llrrrr}
\toprule
Model cell & Vendor & Denials & Overrode & Rate & 95\%% CI \\
\midrule
%s
\bottomrule
\end{tabular}
""" % "\n".join(body)


TABLES = {
    "tab-action-space.tex": action_space,
    "tab-residual.tex": residual,
    "tab-composition.tex": composition,
    "tab-ablation.tex": ablation,
    "tab-crossvendor.tex": crossvendor,
    "tab-app-effort.tex": effort,
}


def _row_keys(tex):
    """The label of every data row in a generated tabular, as a set."""
    return set(_rows_by_key(tex))


def _rows_lost(old, new):
    """Row labels present in the committed table and absent from the rebuild."""
    if not old:
        return set()
    return _row_keys(old) - _row_keys(new)


def _rows_by_key(tex):
    """label -> that data row's text, whitespace-collapsed. Data rows only."""
    import re
    rows = {}
    for line in tex.splitlines():
        if "&" not in line:
            continue
        cell = line.split("&", 1)[0]
        cell = re.sub(r"\\[a-zA-Z]+\s*", " ", cell)
        cell = cell.replace("{", " ").replace("}", " ").replace("\\", " ")
        cell = " ".join(cell.split()).strip(" -")
        if cell:
            rows[cell] = " ".join(line.split())
    return rows


def _rows_changed(old, new):
    """Labels whose row is in BOTH files and whose contents disagree."""
    if not old:
        return []
    a, b = _rows_by_key(old), _rows_by_key(new)
    return sorted(k for k in set(a) & set(b) if a[k] != b[k])


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true",
                    help="overwrite a populated table with an interim "
                         "placeholder; refused by default")
    ap.add_argument("--check", action="store_true",
                    help="do not write; fail if any table on disk is stale")
    args = ap.parse_args()

    if os.path.isdir(REPO):
        os.chdir(REPO)
    else:
        sys.stderr.write("tables.py: cannot resolve the repository root %r; "
                         "the analysis modules resolve paper/data against the "
                         "working directory and would silently check nothing\n"
                         % REPO)
        return 2

    if not os.path.isdir(OUT):
        os.makedirs(OUT)

    stale, wrote, unbuildable, broken, mismatched = [], [], [], [], []
    for name, build in sorted(TABLES.items()):
        path = os.path.join(OUT, name)
        try:
            body = build()
        except SystemExit as exc:
            unbuildable.append((name, "scope guard exit %s: the corpus this "
                                      "table reads is not on this machine"
                                % (exc.code if exc.code is not None else 0)))
            print("  n/a   %-24s cannot be built here; not checked" % name)
            continue
        except Exception as exc:  # noqa: BLE001 - one bad table must not stop the rest
            # A RAISING BUILDER IS A FAILURE, NOT AN ABSENCE. It goes on
            # `broken` as well as `unbuildable`, so it is still listed in the
            # coverage tail AND it reaches the exit code.
            print("  FAIL  %-24s %s: %s" % (name, type(exc).__name__, exc))
            unbuildable.append((name, "%s: %s" % (type(exc).__name__, exc)))
            broken.append(name)
            continue
        if args.check:
            old = ""
            if os.path.exists(path):
                with io.open(path, encoding="utf-8") as fh:
                    old = fh.read()
            lost = _rows_lost(old, body)
            if "not collected" in body and "not collected" not in old and old:
                unbuildable.append(
                    (name, "rebuilt degraded: the arms this table reads have "
                           "not collected on this machine"))
                print("  n/a   %-24s cannot be built here; not checked" % name)
            elif lost:
                changed = _rows_changed(old, body)
                common = len(_row_keys(old) & _row_keys(body))
                unbuildable.append(
                    (name, "rebuilt without %d row(s) whose corpus is absent "
                           "here: %s; %d row label(s) compared, %d disagree"
                           % (len(lost), ", ".join(sorted(lost)),
                              common, len(changed))))
                print("  n/a   %-24s cannot be built here; missing %s"
                      % (name, ", ".join(sorted(lost))))
                if changed:
                    mismatched.append((name, changed))
                    print("  DIFF  %-24s %d row(s) whose corpus IS present "
                          "disagree: %s"
                          % (name, len(changed), ", ".join(changed)))
            elif old != body:
                stale.append(name)
                print("  STALE %-24s regenerate with tables.py" % name)
            else:
                print("  ok    %-24s" % name)
            continue
        degraded = "not collected" in body
        if degraded and os.path.exists(path) and not args.force:
            with io.open(path, encoding="utf-8") as fh:
                old_body = fh.read()
            if "not collected" not in old_body:
                print("  KEPT  %-24s refusing to overwrite real numbers with"
                      " 'not collected' (use --force)" % name)
                stale.append(name)
                continue
        with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(body)
        wrote.append(name)
        print("  wrote %-24s %d lines%s"
              % (name, body.count("\n"), "  [INTERIM]" if degraded else ""))

    if args.check:
        checked = len(TABLES) - len(unbuildable)
        print("")
        print("  --check: %d of %d table(s) checked, %d stale, %d not"
              " checkable here%s"
              % (checked, len(TABLES), len(stale), len(unbuildable),
                 ", %d BROKEN" % len(broken) if broken else ""))
        for name, why in unbuildable:
            print("    n/a   %-24s %s" % (name, why))
        if stale:
            print("")
            print("%d table(s) stale. main.tex would print a number that no"
                  " longer" % len(stale))
            print("follows from the data. Run tables.py and re-read the diff.")
        if mismatched:
            print("")
            print("%d table(s) disagree with the data on a row that WAS"
                  " rebuilt:" % len(mismatched))
            for name, rows in mismatched:
                print("  %-24s %s" % (name, ", ".join(rows)))
            print("Do NOT regenerate these: rows are missing from the rebuild"
                  " and would be")
            print("lost. Reconcile the row against what the generator emits.")
        if broken:
            print("")
            print("%d table generator(s) RAISED. That is not a missing corpus"
                  " and it is not" % len(broken))
            print("an excuse: %s. The number the paper"
                  % ", ".join(sorted(broken)))
            print("prints for that table is currently emitted by nothing.")
        return len(stale) + len(broken) + len(mismatched)
    return len(broken)


if __name__ == "__main__":
    sys.exit(main())
