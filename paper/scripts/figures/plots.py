class NoSource(Exception):
    """The generated table this plot reads is not on this machine."""


class NotEmitted(Exception):
    """No command in this repository emits this figure's numbers, anywhere."""


def _typeset_figures():
    """The figure files main.tex actually \\input s, as basenames."""
    try:
        with io.open(MAIN, encoding="utf-8", errors="replace") as fh:
            src = fh.read()
    except OSError:
        return set()
    src = re.sub(r"(?<!\\)%.*", "", src)
    out = set()
    for stem in re.findall(r"\\(?:input|include)\s*\{([^}]+)\}", src):
        stem = stem.strip()
        if not stem.endswith(".tex"):
            stem += ".tex"
        out.add(os.path.basename(stem))
    return out


# --------------------------------------------------------------- parsing ---

def _bonf_z(k_tests, alpha=0.05):
    """Two-sided z for alpha/k, so a Bonferroni bound uses the whiskers' own
    estimator instead of quietly switching to an exact binomial one."""
    from statistics import NormalDist
    return NormalDist().inv_cdf(1.0 - (alpha / float(k_tests)) / 2.0)


def read_table(name):
    path = os.path.join(OUT, name)
    if not os.path.isfile(path):
        raise NoSource("%s has not been generated; run tables.py" % name)
    with io.open(path, encoding="utf-8") as fh:
        return fh.read()


def cells(line):
    """The `a & b & c \\\\` cells of one LaTeX row, stripped."""
    return [c.strip() for c in line.rstrip().rstrip("\\").split("&")]


NUM = re.compile(r"[-+]?\d+(?:\.\d+)?")


def one_number(text, what):
    m = NUM.search(text.replace(",", ""))
    if not m:
        raise ValueError("no number in %s: %r" % (what, text))
    return float(m.group(0))


def interval(text, what):
    m = re.search(r"\[\s*([-+]?[\d.]+)\s*,\s*([-+]?[\d.]+)\s*\]", text)
    if not m:
        raise ValueError("no interval in %s: %r" % (what, text))
    return float(m.group(1)), float(m.group(2))


def nz(x):
    """Round to one place and kill negative zero."""
    v = round(float(x), 1)
    return 0.0 if v == 0 else v


def exact_count(pct_text, n):
    """The integer count that reproduces a printed `%.1f` share, or raise."""
    want = "%.1f" % float(pct_text)
    hits = [k for k in range(n + 1) if ("%.1f" % (100.0 * k / n)) == want]
    if len(hits) != 1:
        raise ValueError("cannot recover a unique count for %s%% of %d: %r"
                         % (want, n, hits))
    return hits[0]


CARDINAL = {2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six", 7: "Seven"}
ORDINAL = {4: "fourth", 5: "fifth", 6: "sixth", 7: "seventh"}


def rule_count():
    """How many rules the guard has, counted rather than asserted."""
    path = os.path.join(OUT, "ruleset.txt")
    if not os.path.isfile(path):
        raise NoSource("figures/ruleset.txt is absent; the rule count in the "
                       "caption has no source")
    with io.open(path, encoding="utf-8") as fh:
        n = sum(1 for line in fh if line.strip())
    if not n:
        raise ValueError("figures/ruleset.txt is empty")
    return n


def parse_action_space():
    """{block: {shell|tool: (n, k, pct, lo, hi), diff: (pts, lo, hi)}}."""
    text = read_table("tab-action-space.tex")
    blocks, current = {}, None
    for line in text.splitlines():
        if "Every recorded call" in line:
            current = blocks.setdefault("all", {})
            continue
        if "Mutating calls only" in line:
            current = blocks.setdefault("mutating", {})
            continue
        if current is None or "&" not in line or line.lstrip().startswith("%"):
            continue
        c = cells(line)
        if c[0].startswith("Shell") or c[0].startswith("Structured"):
            key = "shell" if c[0].startswith("Shell") else "tool"
            lo, hi = interval(c[4], "%s interval" % key)
            current[key] = (int(one_number(c[1], "calls")),
                            int(one_number(c[2], "refused")),
                            one_number(c[3], "share"), lo, hi)
        elif c[0].startswith("Difference"):
            lo, hi = interval(c[4], "difference interval")
            current["diff"] = (one_number(c[3], "difference"), lo, hi)

    for block in ("all", "mutating"):
        got = blocks.get(block) or {}
        missing = [k for k in ("shell", "tool", "diff") if k not in got]
        if missing:
            raise ValueError("tab-action-space.tex block %r is missing %s; the "
                             "table's shape changed and this plot must be "
                             "re-read, not re-run" % (block, ", ".join(missing)))
    return blocks


LADDER = ["Terse", "Explain", "Padded", "Defer", "Full"]
SHORT = {"Terse": "terse", "Explain": "explain", "Padded": "padded",
         "Defer": "defer", "Full": "full"}


def parse_ablation():
    """([(arm, n, k, pct, lo, hi)] for the refusal-text arms, total arm count)."""
    text = read_table("tab-ablation.tex")
    if "not collected" in text:
        raise NoSource("tab-ablation.tex is the interim placeholder; the arms "
                       "have not collected on this machine")
    found, n_arms = {}, 0
    for line in text.splitlines():
        if "&" not in line or line.lstrip().startswith("%"):
            continue
        c = cells(line)
        arm = c[0].split()[0].rstrip(",")
        if arm not in LADDER or len(c) < 3:
            continue
        n_arms += 1
        # "Full, no system note (control)" also starts with Full. It is a
        # different arm and must not overwrite the matched full arm.
        if c[0].startswith("Full,"):
            continue
        n = int(one_number(c[1], "%s events" % arm))
        pct = one_number(c[2], "%s override" % arm)
        k = exact_count(pct, n)
        lo, hi = wilson(k, n)
        found[arm] = (arm, n, k, pct, 100.0 * lo, 100.0 * hi)

    missing = [a for a in LADDER if a not in found]
    if missing:
        raise ValueError("tab-ablation.tex is missing arm(s) %s; the table's "
                         "shape changed" % ", ".join(missing))
    return [found[a] for a in LADDER], n_arms


