FIGURES = {
    "fig-action-space.tex": action_space,
    "fig-ablation.tex": ablation,
    "fig-reversal.tex": reversal,
}


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="do not write; fail if any plot on disk is stale")
    args = ap.parse_args()

    if not os.path.isdir(OUT):
        os.makedirs(OUT)

    typeset = _typeset_figures()
    stale, wrote, unbuildable, unemitted = [], [], [], []
    broken, missing = [], []
    for name, build in sorted(FIGURES.items()):
        path = os.path.join(OUT, name)
        try:
            body = build()
        except NotEmitted as exc:
            unbuildable.append((name, str(exc)))
            unemitted.append(name)
            if name in typeset:
                missing.append(name)
                print("  FAIL  %-24s main.tex \\input s this and nothing "
                      "emits it" % name)
            else:
                print("  TODO  %-24s no command emits this figure; not "
                      "\\input by main.tex" % name)
            continue
        except NoSource as exc:
            unbuildable.append((name, str(exc)))
            print("  n/a   %-24s cannot be built here; not checked" % name)
            continue
        except SystemExit as exc:
            # An analysis module's scope guard. SystemExit is not an Exception
            # and the handler below does not catch it; tables.py lost four of
            # five tables to exactly this.
            unbuildable.append((name, "scope guard exit %s: the corpus this "
                                      "plot reads is not on this machine"
                                % (exc.code if exc.code is not None else 0)))
            print("  n/a   %-24s cannot be built here; not checked" % name)
            continue
        except Exception as exc:  # noqa: BLE001 - one bad plot must not stop the rest
            print("  FAIL  %-24s %s: %s" % (name, type(exc).__name__, exc))
            unbuildable.append((name, "%s: %s" % (type(exc).__name__, exc)))
            broken.append(name)
            continue

        if args.check:
            old = ""
            if os.path.exists(path):
                with io.open(path, encoding="utf-8") as fh:
                    old = fh.read()
            if old != body:
                stale.append(name)
                print("  STALE %-24s regenerate with plots.py" % name)
            else:
                print("  ok    %-24s" % name)
            continue

        with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(body)
        wrote.append(name)
        print("  wrote %-24s %d lines" % (name, body.count("\n")))

    if args.check:
        checked = len(FIGURES) - len(unbuildable)
        print("")
        print("  --check: %d of %d plot(s) checked, %d stale, %d not"
              " checkable here%s%s"
              % (checked, len(FIGURES), len(stale), len(unbuildable),
                 ", %d emitted by nothing" % len(unemitted) if unemitted
                 else "",
                 ", %d BROKEN" % len(broken + missing)
                 if broken or missing else ""))
        for name, why in unbuildable:
            print("    n/a   %-24s %s" % (name, why))
        if stale:
            print("")
            print("%d plot(s) stale. main.tex would draw a bar that no longer"
                  % len(stale))
            print("follows from the table beside it. Run plots.py and re-read"
                  " the diff.")
        if unemitted:
            print("")
            print("%d figure(s) are emitted by no command on any machine: %s."
                  % (len(unemitted), ", ".join(sorted(unemitted))))
            print("That is a missing builder, not a missing corpus, and it")
            print("does not clear by syncing data. Fatal only once main.tex")
            print("\\input s one of them; until then it is a standing TODO.")
        if missing:
            print("")
            print("%d plot(s) that main.tex typesets are emitted by nothing:"
                  " %s." % (len(missing), ", ".join(sorted(missing))))
            print("The submitted PDF would carry a figure no command emits.")
        if broken:
            print("")
            print("%d plot builder(s) RAISED: %s. That is not an absence and"
                  % (len(broken), ", ".join(sorted(broken))))
            print("it is not an excuse - the figure the paper draws for that")
            print("plot is currently checked by nothing.")
        return len(stale) + len(broken) + len(missing)
    return len(broken) + len(missing)


if __name__ == "__main__":
    sys.exit(main())
